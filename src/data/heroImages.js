// Internal Page Imagery Resolver Function
// ============================================================
export function getInternalHeroImage({
  pageSlug = '',
  courseSlug = '',
  topicSlug = '',
  audienceSlug = '',
} = {}) {
  // 1. Direct Topic Lookup
  if (topicSlug && heroImages.topics[topicSlug]) {
    return heroImages.topics[topicSlug];
  }

  // 2. Direct Audience Lookup
  if (audienceSlug && heroImages.audience[audienceSlug]) {
    return heroImages.audience[audienceSlug];
  }

  // 3. Direct Course Lookup
  if (courseSlug && heroImages.courses[courseSlug]) {
    return heroImages.courses[courseSlug];
  }

  // 4. Direct Static Page Lookup
  if (pageSlug) {
    const cleanSlug = pageSlug.replace(/^[/]+|[/]+$/g, '');
    const mappedKey = {
      'about': 'about',
      'about-us': 'about',
      'mission': 'mission',
      'our-mission': 'mission',
      'vision': 'vision',
      'our-vision': 'vision',
      'why-choose-sky9': 'whySky9',
      'learning-approach': 'learningApproach',
      'our-learning-approach': 'learningApproach',
      'our-commitment': 'commitment',
      'who-can-join': 'whoCanJoin',
      'student-success': 'studentSuccess',
      'student-success-stories': 'studentSuccess',
      'career': 'career',
      'hiring-partners': 'career',
      'certification': 'certification',
      'internship': 'internship',
      'contact': 'contact',
      'contact-us': 'contact',
      'pricing': 'pricing',
      'courses': 'coursesHub',
      'resources': 'resources',
      'resources/learning-overview': 'resources',
      'resources/career-skill-guides': 'guides',
      'resources/frequently-asked-questions': 'faqs',
      'resources/student-success-stories': 'caseStudies',
      'resources/industry-tool-index': 'tools',
      'resources/ebooks': 'ebooks',
      'resources/checklists': 'checklists',
      'resources/templates': 'templates',
      'resources/visual-sitemap-directory': 'sitemap',
      'sitemap': 'sitemap',
      'locations': 'location',
      'resources/ui-design-system': 'designSystem',
    }[cleanSlug];

    if (mappedKey && heroImages[mappedKey]) {
      return heroImages[mappedKey];
    }
    if (heroImages.audience[cleanSlug]) {
      return heroImages.audience[cleanSlug];
    }
    if (heroImages.courses[cleanSlug]) {
      return heroImages.courses[cleanSlug];
    }
    if (heroImages.topics[cleanSlug]) {
      return heroImages.topics[cleanSlug];
    }
    const normalizedTopic = cleanSlug.replace(/-and-/g, '-');
    if (heroImages.topics[normalizedTopic]) {
      return heroImages.topics[normalizedTopic];
    }
  }

  // 5. Safe Fallback
  return heroImages.genericDefault;
}

// Course-specific resolver
export function getCourseHeroImage(slug) {
  return heroImages.courses[slug] || heroImages.genericDefault;
}

// Topic-specific resolver
export function getTopicHeroImage(topicSlug, parentCourseSlug) {
  if (topicSlug) {
    if (heroImages.topics[topicSlug]) {
      return heroImages.topics[topicSlug];
    }
    const normalized = topicSlug.replace(/-and-/g, '-');
    if (heroImages.topics[normalized]) {
      return heroImages.topics[normalized];
    }
  }
  if (parentCourseSlug && heroImages.courses[parentCourseSlug]) {
    return heroImages.courses[parentCourseSlug];
  }
  return heroImages.genericDefault;
}

